"""База всех команд."""

from __future__ import annotations


class Command[ResultT]:
    """Команда — намерение изменить состояние (именуется в повелительном наклонении).

    Диспетчеризуется через CommandBus; обработчик ровно один, он возвращает
    ``ResultT`` (его же возвращает ``CommandBus.dispatch``). Команды — frozen
    dataclasses без поведения.

    ВАЖНО: поля команд могут содержать секреты (например, Bot Token), поэтому
    шина логирует только имя типа команды — никогда не поля.
    """

    __slots__ = ()
